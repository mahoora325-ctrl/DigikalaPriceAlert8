package ir.example.digikalapricealert

/**
 * برای تبدیل اعداد لاتین به فارسی، فقط در نمایش (نه در ذخیره‌سازی/محاسبات
 * داخلی) استفاده می‌شود؛ مقادیر خام (مثل thresholdToman یا تاریخ ذخیره‌شده
 * برای مرتب‌سازی) همیشه با ارقام لاتین می‌مانند تا محاسبات و مرتب‌سازی درست
 * کار کنند.
 *
 * چون کل برنامه راست‌به‌چپ (RTL) اجباری شده، رشته‌های عددیِ ترکیبی (مثل
 * «۱۴۰۵/۰۵/۰۸ ۱۹:۰۰» یا «۴٬۱۱۹٬۱۰۰») اگر بدون محافظت نمایش داده شوند، ممکن
 * است الگوریتم bidi اندروید ترتیب بخش‌های داخلی‌شان (مثلاً ساعت و تاریخ) را
 * جابه‌جا نشان دهد. برای جلوگیری از این به‌هم‌ریختگی، هر رشته‌ی عددیِ نمایشی
 * بین دو نویسه‌ی جهت‌دهِ یونیکد (Left-to-Right Isolate و Pop Directional
 * Isolate) قرار می‌گیرد تا همیشه به همان ترتیبی که نوشته شده نمایش داده شود.
 */
object PersianNumberUtils {

    // فونت طنین برای ارقام ۴، ۵ و ۶ گلیف اختصاصی فارسی دارد، ولی برای بقیه‌ی
    // ارقام (۰،۱،۲،۳،۷،۸،۹) گلیف فارسی ندارد و اندروید به فونت دیگری سقوط
    // می‌کند (همان چیزی که باعث ناهماهنگی فونت اعداد می‌شد). چون این فونت
    // برای شکل عربیِ همه‌ی ارقام گلیف کامل دارد، برای رقم‌هایی که گلیف فارسی
    // ندارند از شکل عربی (که تفاوت چندانی با فارسی ندارد) استفاده می‌کنیم تا
    // همیشه همان یک فونت طنین به کار برود.
    private val displayDigits = charArrayOf(
        '٠', '١', '٢', '٣', // عربی: چون طنین گلیف فارسی این‌ها را ندارد
        '۴', '۵', '۶',       // فارسی: طنین گلیف اختصاصی این‌ها را دارد
        '٧', '٨', '٩'        // عربی: چون طنین گلیف فارسی این‌ها را ندارد
    )
    private const val LRI = "\u2066" // Left-to-Right Isolate
    private const val PDI = "\u2069" // Pop Directional Isolate

    /** ارقام لاتین را به ارقامی تبدیل می‌کند که فونت طنین برایشان گلیف دارد، بدون تغییر ترتیب نمایش. */
    fun toPersianDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            if (ch in '0'..'9') {
                sb.append(displayDigits[ch - '0'])
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    /** رشته را در نویسه‌های جهت‌ده ایزوله می‌کند تا ترتیب داخلی‌اش در متن راست‌به‌چپ به‌هم نریزد. */
    private fun isolate(text: String): String = "$LRI$text$PDI"

    /** تبدیل به فارسی + ایزوله‌سازی جهت؛ برای هر متن عددیِ آماده‌ی نمایش (تاریخ، شمارنده و…) استفاده شود. */
    fun forDisplay(input: String): String = isolate(toPersianDigits(input))

    /** قیمت را با جداکننده‌ی هزارگان فارسی («٬») و ارقام فارسی فرمت می‌کند. */
    fun formatToman(value: Long): String {
        // Locale.US عمداً صریح است؛ در گوشی با زبان فارسی، فرمت‌کننده‌ی جاوا
        // بدون این کار خودش ارقام را به ارقام فارسیِ سیستم (که با فونت طنین
        // ناسازگارند) تبدیل می‌کرد، پیش از اینکه منطق خودمان اجرا شود.
        val withLatinSeparator = String.format(java.util.Locale.US, "%,d", value)
        val withPersianSeparator = withLatinSeparator.replace(',', '٬')
        return isolate(toPersianDigits(withPersianSeparator))
    }
}
